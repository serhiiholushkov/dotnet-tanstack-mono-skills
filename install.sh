manifest_path() { printf '%s/%s/%s' "$target" "$STATE_DIR" "$MANIFEST_NAME"; }

load_catalog_state() {
  local mp rel fp extra input
  mp="$(manifest_path)"
  safe_parents "$STATE_DIR/$MANIFEST_NAME" || die "the catalog manifest must have real directory parents"
  [ ! -L "$mp" ] || die "refusing to use a symlinked catalog manifest"
  if [ -e "$mp" ]; then
    [ -f "$mp" ] || die "catalog manifest is not a regular file"
    input="$tmp_root/current-manifest"
    awk '{ sub(/\r$/, ""); print }' "$mp" > "$input"
    grep -Fqx "# catalog: $CATALOG_ID" "$input" || die "manifest belongs to another catalog"
    grep -Fqx '# format: 2' "$input" || die "unsupported manifest format"
    while IFS=$'\t' read -r rel fp extra; do
      case "$rel" in "" | \#*) continue ;; esac
      valid_path "$rel" || die "unsafe manifest path '$rel'"
      [ -z "$extra" ] || die "malformed manifest entry '$rel'"
      if ! printf '%s\n' "$fp" | grep -Eq '^(F:[0-9]+:[0-9]+:[x-]|L:[0-9]+:[0-9]+|legacy)$'; then
        die "invalid fingerprint for '$rel'"
      fi
      printf '%s\t%s\n' "$rel" "$fp" >> "$previous_manifest"
    done < "$input"
  fi
  mp="$target/$catalog_dir/$MANIFEST_NAME"
  if [ -e "$mp" ] || [ -L "$mp" ]; then
    safe_parents "$catalog_dir/$MANIFEST_NAME" || die "unsafe legacy manifest location"
    [ -f "$mp" ] && [ ! -L "$mp" ] || die "legacy manifest is not a regular file"
    grep -q '^# agent-harness install manifest' "$mp" || die "unrecognized legacy manifest"
    [ "$force" = 1 ] || die "legacy installation has no fingerprints; review local edits and re-run with --force (or --hard) to migrate"
    legacy_manifest="$mp"
    legacy_entries="$tmp_root/legacy-manifest"
    awk '{ sub(/\r$/, ""); print }' "$mp" > "$legacy_entries"
    while IFS= read -r rel; do
      case "$rel" in "" | \#*) continue ;; esac
      valid_path "$rel" || die "unsafe legacy manifest path '$rel'"
      printf '%s\tlegacy\n' "$rel" >> "$previous_manifest"
    done < "$legacy_entries"
  fi
  awk -F '\t' '!seen[$1]++' "$previous_manifest" > "$tmp_root/unique"
  mv "$tmp_root/unique" "$previous_manifest"
  cat "$previous_manifest" > "$manifest_tmp"
}

effective_manifest() {
  awk -F '\t' '{ state[$1] = $2 } END { for (p in state) if (state[p] != "-") print p "\t" state[p] }' "$manifest_tmp" | LC_ALL=C sort
}

prune_parents() {
  [ "$dry_run" = 0 ] || return 0
  local d
  d="$(dirname "$1")"
  while [ "$d" != "." ] && [ -d "$target/$d" ] && [ ! -L "$target/$d" ]; do
    rmdir "$target/$d" 2>/dev/null || break
    d="$(dirname "$d")"
  done
}

write_manifest() {
  local rel="$STATE_DIR/$MANIFEST_NAME" staged
  effective_manifest > "$tmp_root/effective"
  if [ "$dry_run" = 1 ]; then say "  + $rel (ownership catalog)"; return 0; fi
  safe_parents "$rel" || return 1
  [ ! -L "$target/$rel" ] || return 1
  if [ "$do_uninstall" = 1 ] && [ ! -s "$tmp_root/effective" ]; then
    rm -f "$target/$rel"
    prune_parents "$rel"
  else
    mkdir -p "$target/$STATE_DIR"
    staged="$(mktemp "$target/$STATE_DIR/.manifest.XXXXXX")"
    {
      printf '# agent-harness install manifest; do not edit\n'
      printf '# catalog: %s\n# format: 2\n' "$CATALOG_ID"
      printf '# source: %s @ %s\n' "$src_label" "$src_rev"
      printf '# installer: %s\n' "$INSTALLER_VERSION"
      printf '# options: --harness %s --packs %s%s%s%s\n' \
        "$(printf '%s' "$harnesses" | tr ' ' ',')" "$(printf '%s' "$packs" | tr ' ' ',')" \
        "$([ "$with_hooks" = 1 ] && printf ' --hooks')" \
        "$([ "$with_git_hooks" = 1 ] && printf ' --git-hooks')" \
        "$([ "$touch_root" = 0 ] && printf ' --no-root')"
      cat "$tmp_root/effective"
    } > "$staged"
    chmod 644 "$staged"
    mv -f "$staged" "$target/$rel"
  fi
}

remove_path() {
  local rel="$1" old="$2" current
  valid_path "$rel" || die "unsafe removal path '$rel'"
  seen "$rel"
  if ! safe_parents "$rel"; then action preserved "$rel"; return 0; fi
  current="$(fingerprint "$target/$rel")"
  if [ -z "$current" ]; then
    record "$rel" "-"
    prune_parents "$rel"
    return 0
  fi
  if [ "$current" = "directory-or-special" ]; then
    warn "$rel is now a directory or special file; left untouched even with --force"
    action preserved "$rel"
    return 0
  fi
  if [ "$current" != "$old" ] && [ "$force" = 0 ]; then
    warn "$rel was locally modified; preserved instead of removing it (use --force for catalog-owned edits)"
    action preserved "$rel"
    return 0
  fi
  if [ "$dry_run" = 1 ]; then say "  - $rel"; else rm -f "$target/$rel"; prune_parents "$rel"; fi
  record "$rel" "-"
  action removed "$rel"
}

remove_obsolete() {
  local rel old
  while IFS=$'\t' read -r rel old; do
    if ! grep -Fqx -- "$rel" "$seen_tmp"; then remove_path "$rel" "$old"; fi
  done < "$previous_manifest"
}

remove_obsolete_shared() {
  local rel old
  while IFS=$'\t' read -r rel old; do
    case "$rel" in
      docs/* | .agents/skills/* | .agents/rules/* | .agents/hooks/* | .agents/templates/*)
        if ! grep -Fqx -- "$rel" "$seen_tmp"; then remove_path "$rel" "$old"; fi
        ;;
    esac
  done < "$previous_manifest"
}

migrate_legacy() {
  [ -n "$legacy_manifest" ] || return 0
  say "Migrating legacy installation; --force authorizes replacement of its listed files only"
  local rel
  while IFS= read -r rel; do
    case "$rel" in "" | \#*) continue ;; esac
    remove_path "$rel" "$(previous_fingerprint "$rel")"
  done < "$legacy_entries"
}

retire_legacy_manifest() {
  [ -n "$legacy_manifest" ] || return 0
  if effective_manifest | awk -F '\t' '$2 == "legacy" { found = 1 } END { exit !found }'; then
    warn "Some legacy paths were preserved; the legacy manifest was retained for a later --force migration"
    return 0
  fi
  if [ "$dry_run" = 1 ]; then
    say "  - $catalog_dir/$MANIFEST_NAME"
  else
    rm -f "$legacy_manifest"
    prune_parents "$catalog_dir/$MANIFEST_NAME"
  fi
}

run_uninstall() {
  prepare_workspace
  resolve_target
  if [ ! -e "$(manifest_path)" ] && [ ! -e "$target/$catalog_dir/$MANIFEST_NAME" ]; then die "no manifest for $CATALOG_ID in $target"; fi
  load_catalog_state
  persist_manifest=1
  say "Uninstalling $CATALOG_ID from $target"
  local rel old
  while IFS=$'\t' read -r rel old; do remove_path "$rel" "$old"; done < "$previous_manifest"
  retire_legacy_manifest
  write_manifest
  persist_manifest=0
  print_warnings
}

print_warnings() {
  if [ -s "$warnings_file" ]; then printf '\nWarnings:\n'; cat "$warnings_file"; fi
}

# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

run_install() {
  harnesses="$(normalize_harnesses "$harness_arg")"
  packs="$(normalize_packs "$packs_arg")"
  prepare_workspace
  resolve_source
  resolve_target
  load_catalog_state
  persist_manifest=1

  say "Installing $CATALOG_ID"
  say "  source : $src_label @ $src_rev"
  say "  target : $target"
  say "  harness: $harnesses"
  say "  packs  : $packs"
  [ "$dry_run" = 1 ] && say "  mode   : dry run (nothing is written)"
  say ""

  if [ -f "$(manifest_path)" ]; then say "Previous catalog found; safely updating owned files"; fi
  migrate_legacy

  install_catalog
  remove_obsolete_shared
  install_root_files
  if [ "$touch_root" = 0 ]; then seen "AGENTS.md"; seen "CLAUDE.md"; fi

  local h
  for h in $harnesses; do
    say ""
    say "== $h"
    case "$h" in
      claude)
        install_rules claude
        ;;
      copilot)
        install_rules copilot
        ;;
      codex)
        say "Skills: shared $SHARED_DIR/skills/; rules: linked from AGENTS.md ($SHARED_DIR/rules/)"
        ;;
      cursor)
        install_rules cursor
        ;;
    esac
  done
  install_skill_aliases

  say ""
  install_hooks
  install_git_hooks
  remove_obsolete
  retire_legacy_manifest
  write_manifest
  persist_manifest=0

  say ""
  say "Done. Catalog: $n_catalog resources, $n_skills shared skills, $n_rules rule adapters, $n_hooks hook configs."
  say "  Written: $(awk -F '\t' '$1 == "written" || $1 == "linked" { n++ } END { print n+0 }' "$actions_file"); preserved/skipped: $(awk -F '\t' '$1 == "preserved" || $1 == "skipped" { n++ } END { print n+0 }' "$actions_file")."
  say ""
  say "Next steps:"
  say "  - Review and commit the shared catalog, documentation, adapters, symlinks, and $STATE_DIR/$MANIFEST_NAME."
  say "  - Edit skills in $SHARED_DIR/skills/ and project documentation in docs/. Reinstalls preserve local edits."
  say "  - Re-run to update unchanged owned files; --force (or --hard) replaces owned edits, never unmanaged content."
  say "  - --uninstall removes unchanged owned files; add --force to also remove owned edits."
  has_harness copilot && say "  - VS Code: keep chat.useAgentsMdFile on; enable chat.useCustomizationsInParentRepositories if the repo opens from a subfolder."
  if [ "$with_hooks" = 1 ] && has_harness copilot; then
    say "  - VS Code hooks are Preview: enable chat.useHooks and trust the workspace for .github/hooks/guards.json to run."
  fi
  has_harness codex && say "  - Codex: invoke skills with \$<name> or /skills; rules are reached through AGENTS.md links."
  [ "$with_hooks" = 1 ] || say "  - Optional: add --hooks and/or --git-hooks — see $SHARED_DIR/hooks/README.md."
  print_warnings
}

main() {
  parse_args "$@"
  if [ "$do_uninstall" = 1 ]; then
    run_uninstall
  else
    run_install
  fi
}

main "$@"
