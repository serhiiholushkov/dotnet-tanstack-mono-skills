install_catalog() {
  say "Shared catalog -> $SHARED_DIR/; documentation -> docs/"
  local item f dest listing
  for item in $CATALOG_ITEMS; do
    [ -e "$src/$item" ] || continue
    listing="$(files_under "$src" "$item")"
    while IFS= read -r f; do
      case "$f" in docs/*) dest="$f" ;; *) dest="$SHARED_DIR/$f" ;; esac
      install_resource "$f" "$dest"
      n_catalog=$((n_catalog + 1))
    done < "$listing"
  done
  if [ -f "$src/LICENSE" ]; then copy_file "$src/LICENSE" "$STATE_DIR/LICENSE"; fi
  install_shared_skills
}

files_under() {
  local listing
  listing="$(mktemp "$tmp_root/list.XXXXXX")"
  if ! (cd "$1" && find "$2" -type f ! -name .DS_Store -print | LC_ALL=C sort) > "$listing"; then
    die "could not enumerate '$1/$2'; no obsolete-file cleanup will be performed"
  fi
  printf '%s' "$listing"
}

install_resource() {
  case "$1" in
    *.md) rewrite_links "$(dirname "$1")" "$(dirname "$2")" "${3:-}" < "$src/$1" | write_file "$2" ;;
    *) copy_file "$src/$1" "$2" ;;
  esac
}

install_shared_skills() {
  local d name f rel listing
  if [ -f "$src/skills/README.md" ]; then install_resource "skills/README.md" "$SHARED_DIR/skills/README.md"; fi
  for d in "$src/skills"/*/; do
    [ -f "$d/SKILL.md" ] || continue
    name="$(basename "$d")"
    rel="$SHARED_DIR/skills/$name"
    if ! safe_parents "$rel/SKILL.md"; then action skipped "$rel"; continue; fi
    if [ -L "$target/$rel" ] || { [ -e "$target/$rel" ] && ! owned_tree "$rel"; }; then
      warn "$rel is an unmanaged skill or a symlink; the entire skill was left untouched"
      action skipped "$rel"
      continue
    fi
    listing="$(files_under "$src" "skills/$name")"
    while IFS= read -r f; do
      install_resource "$f" "$SHARED_DIR/$f" "skills/$name"
    done < "$listing"
    if [ "$dry_run" = 0 ] && { [ -z "$(tracked_fingerprint "$rel/SKILL.md")" ] || [ ! -f "$target/$rel/SKILL.md" ] || [ -L "$target/$rel/SKILL.md" ]; }; then
      warn "$rel/SKILL.md is not an installed regular catalog file; no Claude alias will be created"
      continue
    fi
    printf '%s\n' "$name" >> "$accepted_skills"
    n_skills=$((n_skills + 1))
  done
}

install_root_files() {
  [ "$touch_root" = 1 ] || return 0
  local label="AGENTS.md"
  has_harness claude && label="$label + CLAUDE.md"
  say "Contract -> $label"

  {
    printf '<!-- %s; catalog: %s; local edits are preserved unless --force is used -->\n' "$MARKER" "$CATALOG_ID"
    rewrite_links "" "" < "$src/AGENTS.md"
  } | write_file "AGENTS.md"
  n_root=$((n_root + 1))

  if has_harness claude; then
    {
      printf '<!-- %s; catalog: %s -->\n' "$MARKER" "$CATALOG_ID"
      printf '@AGENTS.md\n'
    } | write_file "CLAUDE.md"
    n_root=$((n_root + 1))
  fi
}

# install_rules HARNESS
install_rules() {
  local harness="$1" dest pack f name applies desc rel ext globs g canonical linkdir
  case "$harness" in
    claude) dest=".claude/rules"; ext=".md" ;;
    copilot) dest=".github/instructions"; ext=".instructions.md" ;;
    cursor) dest=".cursor/rules"; ext=".mdc" ;;
    *) return 0 ;;
  esac
  say "Rules ($packs) -> $dest/"
  for pack in $packs; do
    for f in "$src/rules/$pack"/*.md; do
      [ -f "$f" ] || continue
      name="$(basename "$f" .md)"
      canonical="$SHARED_DIR/rules/$pack/$name.md"
      linkdir="rules/$pack"
      if [ "$dry_run" = 0 ]; then
        if [ -z "$(tracked_fingerprint "$canonical")" ] || ! safe_parents "$canonical" || [ -L "$target/$canonical" ] || [ ! -f "$target/$canonical" ]; then
          warn "$canonical is not an installed regular catalog file; its native adapter was skipped"
          continue
        fi
        f="$target/$canonical"
        linkdir="$SHARED_DIR/rules/$pack"
      fi
      applies="$(fm_value appliesTo "$f")"
      desc="$(fm_raw description "$f")"
      rel="$dest/$pack-$name$ext"
      globs="$(printf '%s' "$applies" | sed 's/[[:space:]]*,[[:space:]]*/,/g')"
      {
        printf -- '---\n'
        [ -n "$desc" ] && printf 'description: %s\n' "$desc"
        case "$harness" in
          copilot)
            printf "applyTo: '%s'\n" "$applies"
            ;;
          claude)
            if [ "$applies" != "**/*" ] && [ -n "$applies" ]; then
              printf 'paths:\n'
              for g in $(printf '%s' "$globs" | tr ',' ' '); do printf "  - '%s'\n" "$g"; done
            fi
            ;;
          cursor)
            if [ "$applies" = "**/*" ] || [ -z "$applies" ]; then
              printf 'alwaysApply: true\n'
            else
              printf 'globs: %s\n' "$(printf '%s' "$globs" | sed 's/,/, /g')"
              printf 'alwaysApply: false\n'
            fi
            ;;
        esac
        printf -- '---\n'
        body_of "$f" | rewrite_links "$linkdir" "$dest"
      } | write_file "$rel"
      n_rules=$((n_rules + 1))
    done
  done
}

detect_symlinks() {
  local probe reason
  [ "$dry_run" = 0 ] || return 0
  if ! safe_parents ".claude/skills/probe"; then symlinks=0; return 0; fi
  mkdir -p "$target/.claude/skills"
  probe="$(mktemp -d "$target/.claude/skills/.link-probe.XXXXXX")"
  printf 'probe\n' > "$probe/target"
  if ln -s "target" "$probe/link" 2> "$tmp_root/link-error" && [ -L "$probe/link" ]; then
    symlinks=1
  else
    symlinks=0
    reason="$(cat "$tmp_root/link-error")"
    [ -n "$reason" ] || reason="ln did not create a real symbolic link"
    warn "Symlinks are unavailable; copying Claude skills instead: $reason"
  fi
  rm -f "$probe/link" "$probe/target"
  rmdir "$probe"
}

can_link_directory() {
  local rel="$1" f p old current listing
  listing="$(mktemp "$tmp_root/entries.XXXXXX")"
  if ! find "$target/$rel" -mindepth 1 -print > "$listing"; then
    die "could not inspect '$rel'; its copied skill directory will not be replaced"
  fi
  while IFS= read -r f; do
    p="${f#"$target/"}"
    if [ -d "$f" ] && [ ! -L "$f" ]; then
      owned_tree "$p" || return 1
    else
      old="$(previous_fingerprint "$p")"
      [ -n "$old" ] || return 1
      current="$(fingerprint "$f")"
      if [ "$current" != "$old" ] && [ "$force" = 0 ]; then return 1; fi
    fi
  done < "$listing"
}

clear_owned_tree() {
  local rel="$1" p old
  while IFS=$'\t' read -r p old; do
    case "$p" in "$rel"/*) remove_path "$p" "$old" ;; esac
  done < "$previous_manifest"
}

install_skill_aliases() {
  has_harness claude || return 0
  say "Claude skills -> links to $SHARED_DIR/skills/ (copies if unavailable)"
  detect_symlinks
  local name rel f old current use_link listing
  while IFS= read -r name; do
    rel=".claude/skills/$name"
    use_link="$symlinks"
    if ! safe_parents "$rel"; then continue; fi
    if [ -d "$target/$rel" ] && [ ! -L "$target/$rel" ]; then
      if ! owned_tree "$rel"; then
        warn "$rel is an unmanaged skill; left untouched"
        action skipped "$rel"
        continue
      fi
      if [ "$use_link" = 1 ]; then
        if can_link_directory "$rel"; then
          clear_owned_tree "$rel"
        fi
        if [ -d "$target/$rel" ]; then
          use_link=0
          warn "$rel contains preserved content; keeping and updating the copied skill instead of replacing its directory"
        fi
      fi
    fi
    if [ "$use_link" = 1 ]; then
      install_link "$rel" "../../$SHARED_DIR/skills/$name"
    else
      if [ -L "$target/$rel" ] || { [ -e "$target/$rel" ] && [ ! -d "$target/$rel" ]; }; then
        old="$(previous_fingerprint "$rel")"
        current="$(fingerprint "$target/$rel")"
        if [ -z "$old" ] || { [ "$current" != "$old" ] && [ "$force" = 0 ]; }; then
          warn "$rel is unmanaged or locally modified; left untouched"
          seen "$rel"
          action preserved "$rel"
          continue
        fi
        remove_path "$rel" "$old"
        if [ "$dry_run" = 0 ] && { [ -e "$target/$rel" ] || [ -L "$target/$rel" ]; }; then continue; fi
      fi
      if [ "$dry_run" = 1 ]; then
        listing="$(files_under "$src" "skills/$name")"
        while IFS= read -r f; do install_resource "$f" "$rel/${f#"skills/$name/"}" "skills/$name"; done < "$listing"
      else
        listing="$(files_under "$target/$SHARED_DIR/skills/$name" ".")"
        while IFS= read -r f; do
          f="${f#./}"
          copy_file "$target/$SHARED_DIR/skills/$name/$f" "$rel/$f"
        done < "$listing"
      fi
    fi
  done < "$accepted_skills"
}

guard_cmd() { printf '%s/hooks/scripts/guard-generated-files --stdin-json' "$1"; }

hook_config_content() {
  case "$1" in
    .claude/settings.json)
      cat <<EOF
{
  "hooks": {
    "PreToolUse": [
      {
        "matcher": "Edit|Write",
        "hooks": [
          { "type": "command", "command": "\${CLAUDE_PROJECT_DIR}/$(guard_cmd "$SHARED_DIR")" }
        ]
      }
    ]
  }
}
EOF
      ;;
    .github/hooks/guards.json)
      cat <<EOF
{
  "hooks": {
    "PreToolUse": [
      { "type": "command", "command": "$(guard_cmd "$SHARED_DIR")" }
    ]
  }
}
EOF
      ;;
    .cursor/hooks.json)
      cat <<EOF
{
  "version": 1,
  "hooks": {
    "preToolUse": [
      { "command": "$(guard_cmd "$SHARED_DIR")" }
    ]
  }
}
EOF
      ;;
  esac
}

# Existing unmanaged JSON is never merged or adopted.
install_hook_config() {
  local rel="$1"
  if { [ -e "$target/$rel" ] || [ -L "$target/$rel" ]; } && [ -z "$(previous_fingerprint "$rel")" ]; then
    warn "$rel is unmanaged; merge this hook yourself:"$'\n'"$(hook_config_content "$rel")"
    seen "$rel"
    action skipped "$rel"
    return 0
  fi
  hook_config_content "$rel" | write_file "$rel"
  n_hooks=$((n_hooks + 1))
}

install_hooks() {
  [ "$with_hooks" = 1 ] || return 0
  say "Hook configs"
  has_harness claude && install_hook_config ".claude/settings.json"
  has_harness copilot && install_hook_config ".github/hooks/guards.json"
  has_harness cursor && install_hook_config ".cursor/hooks.json"
  has_harness codex && say "  = codex: no pinned hook schema; use --git-hooks and CI (see $SHARED_DIR/hooks/README.md)"
  return 0
}

git_hook_content() {
  case "$1" in
    pre-commit)
      cat <<EOF
#!/bin/sh
# $MARKER — re-run install.sh --git-hooks instead of editing
root="\$(git rev-parse --show-toplevel)"
"\$root/$SHARED_DIR/hooks/scripts/guard-generated-files" --staged || exit 1
"\$root/$SHARED_DIR/hooks/scripts/format-gate" || exit 1
EOF
      ;;
    pre-push)
      cat <<EOF
#!/bin/sh
# $MARKER — re-run install.sh --git-hooks instead of editing
root="\$(git rev-parse --show-toplevel)"
"\$root/$SHARED_DIR/hooks/scripts/verify-gate" || exit 1
EOF
      ;;
  esac
}

install_git_hooks() {
  [ "$with_git_hooks" = 1 ] || return 0
  say "Git hooks -> .git/hooks/"
  local hooks_path hook rel
  if [ ! -d "$target/.git" ]; then
    warn "--git-hooks: $target is not a git repository root; skipped"
    return 0
  fi
  hooks_path="$(git -C "$target" config --get core.hooksPath 2>/dev/null || true)"
  if [ -n "$hooks_path" ]; then
    warn "--git-hooks: core.hooksPath is set ($hooks_path); add the hooks there yourself (see $SHARED_DIR/hooks/README.md)"
    return 0
  fi
  for hook in pre-commit pre-push; do
    rel=".git/hooks/$hook"
    git_hook_content "$hook" | write_file "$rel" 1
    n_hooks=$((n_hooks + 1))
  done
}

