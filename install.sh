#!/usr/bin/env bash
# install.sh — install the agent harness catalog into a consuming repository.
#
# Vendors the canonical catalog into <target>/<dir>/ and generates the
# harness-specific copies (Claude Code, GitHub Copilot / VS Code, Codex, Cursor)
# with frontmatter translated and relative links rewritten to point back at the
# vendored catalog. Everything it writes is recorded in a manifest so re-runs
# are clean and --uninstall is exact.
#
# Works from a checkout (./install.sh) or piped:
#   curl -fsSL https://raw.githubusercontent.com/serhiiholushkov/dotnet-tanstack-mono-skills/main/install.sh \
#     | bash -s -- --target .
#
# Requires: bash 3.2+, awk, sed, find, git (only when the catalog must be cloned).
set -euo pipefail

readonly INSTALLER_VERSION="1.0.0"
readonly DEFAULT_REPO="https://github.com/serhiiholushkov/dotnet-tanstack-mono-skills.git"
readonly ALL_HARNESSES="claude copilot codex cursor"
readonly ALL_PACKS="common csharp dotnet-api typescript web monorepo testing"
readonly CATALOG_ITEMS="AGENTS.md LICENSE docs rules skills agents commands hooks templates"
readonly MARKER="agent-harness: generated by install.sh"
readonly MANIFEST_NAME=".install-manifest"

HARNESS_REPO="${HARNESS_REPO:-$DEFAULT_REPO}"

target="."
harness_arg="all"
packs_arg="all"
catalog_dir="harness"
with_hooks=0
with_git_hooks=0
touch_root=1
dry_run=0
do_uninstall=0
force=0
git_ref=""
source_arg=""

src=""            # resolved catalog source (absolute)
src_label=""      # human-readable origin
src_rev=""        # commit when known
tmp_root=""       # temp dir for clones / manifest staging
manifest_tmp=""
harnesses=""
packs=""

n_rules=0 n_skills=0 n_agents=0 n_commands=0 n_hooks=0 n_catalog=0 n_root=0
warnings=""

# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

usage() {
  cat <<EOF
install.sh v$INSTALLER_VERSION — install the agent harness into a repository.

Usage:
  ./install.sh [options]
  curl -fsSL <raw-url>/install.sh | bash -s -- [options]

Options:
  --target DIR       Consuming repository root (default: current directory)
  --harness LIST     all | comma list of: claude, copilot (alias: vscode), codex, cursor
                     (default: all)
  --packs LIST       Rule packs to install always-on: all | api | web | reviewer |
                     comma list of: $ALL_PACKS
                     (default: all). Roles: api = common,csharp,dotnet-api,testing;
                     web = common,typescript,web,testing; reviewer = common,monorepo.
  --dir NAME         Folder for the vendored catalog inside the target (default: harness)
  --hooks            Also write harness hook configs (.claude/settings.json,
                     .github/hooks/guards.json, .cursor/hooks.json) when absent
  --git-hooks        Also install git pre-commit / pre-push hooks into .git/hooks
  --no-root          Do not write AGENTS.md / CLAUDE.md at the target root
  --force            Overwrite an existing, unmanaged AGENTS.md / CLAUDE.md
  --source DIR       Use this catalog checkout instead of the script's own directory
  --ref REF          Git ref to clone when the catalog is fetched (branch or tag)
  --dry-run          Print what would be written; change nothing
  --uninstall        Remove everything a previous run recorded in <dir>/$MANIFEST_NAME
  -h, --help         This text

Environment:
  HARNESS_REPO       Clone URL used when the catalog is not found locally
                     (default: $DEFAULT_REPO)

What gets installed where is documented in docs/install.md.
EOF
}

die() { printf 'install.sh: error: %s\n' "$*" >&2; exit 1; }
say() { printf '%s\n' "$*"; }
warn() {
  printf 'install.sh: warning: %s\n' "$*" >&2
  warnings="${warnings}  - $*"$'\n'
}

parse_args() {
  while [ $# -gt 0 ]; do
    case "$1" in
      --target=*) target="${1#*=}" ;;
      --target) [ $# -ge 2 ] || die "--target needs a value"; target="$2"; shift ;;
      --harness=*) harness_arg="${1#*=}" ;;
      --harness) [ $# -ge 2 ] || die "--harness needs a value"; harness_arg="$2"; shift ;;
      --packs=*) packs_arg="${1#*=}" ;;
      --packs) [ $# -ge 2 ] || die "--packs needs a value"; packs_arg="$2"; shift ;;
      --dir=*) catalog_dir="${1#*=}" ;;
      --dir) [ $# -ge 2 ] || die "--dir needs a value"; catalog_dir="$2"; shift ;;
      --source=*) source_arg="${1#*=}" ;;
      --source) [ $# -ge 2 ] || die "--source needs a value"; source_arg="$2"; shift ;;
      --ref=*) git_ref="${1#*=}" ;;
      --ref) [ $# -ge 2 ] || die "--ref needs a value"; git_ref="$2"; shift ;;
      --hooks) with_hooks=1 ;;
      --git-hooks) with_git_hooks=1 ;;
      --no-root) touch_root=0 ;;
      --force) force=1 ;;
      --dry-run) dry_run=1 ;;
      --uninstall) do_uninstall=1 ;;
      -h | --help) usage; exit 0 ;;
      *) die "unknown option: $1 (see --help)" ;;
    esac
    shift
  done

  case "$catalog_dir" in
    "" | . | .. | /* | *..* | */*) die "--dir must be a single folder name inside the target (got '$catalog_dir')" ;;
  esac
}

normalize_harnesses() {
  local raw="$1" h out=""
  [ "$raw" = "all" ] && raw="$ALL_HARNESSES"
  for h in $(printf '%s' "$raw" | tr ',' ' '); do
    case "$h" in
      vscode | github | copilot) h="copilot" ;;
      claude | codex | cursor) ;;
      *) die "unknown harness '$h' (choose from: $ALL_HARNESSES)" ;;
    esac
    case " $out " in *" $h "*) ;; *) out="$out $h" ;; esac
  done
  printf '%s' "${out# }"
}

normalize_packs() {
  local raw="$1" p out=""
  case "$raw" in
    all) raw="$ALL_PACKS" ;;
    api) raw="common csharp dotnet-api testing" ;;
    web) raw="common typescript web testing" ;;
    reviewer) raw="common monorepo" ;;
  esac
  for p in $(printf '%s' "$raw" | tr ',' ' '); do
    case " $ALL_PACKS " in
      *" $p "*) ;;
      *) die "unknown rule pack '$p' (choose from: $ALL_PACKS)" ;;
    esac
    case " $out " in *" $p "*) ;; *) out="$out $p" ;; esac
  done
  printf '%s' "${out# }"
}

has_harness() { case " $harnesses " in *" $1 "*) return 0 ;; esac; return 1; }

# ---------------------------------------------------------------------------
# Source resolution
# ---------------------------------------------------------------------------

looks_like_catalog() {
  [ -f "$1/AGENTS.md" ] && [ -d "$1/skills" ] && [ -d "$1/rules" ] && [ -f "$1/docs/architecture.md" ]
}

cleanup() {
  [ -n "$tmp_root" ] && [ -d "$tmp_root" ] && rm -rf "$tmp_root"
  return 0
}

resolve_source() {
  tmp_root="$(mktemp -d 2>/dev/null || mktemp -d -t harness)"
  trap cleanup EXIT

  local script_dir=""
  if [ -n "$source_arg" ]; then
    [ -d "$source_arg" ] || die "--source '$source_arg' is not a directory"
    looks_like_catalog "$source_arg" || die "--source '$source_arg' does not look like the harness catalog"
    src="$(cd "$source_arg" && pwd -P)"
    src_label="$src"
  else
    if [ -n "${BASH_SOURCE[0]:-}" ] && [ "${BASH_SOURCE[0]}" != "bash" ]; then
      script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" 2>/dev/null && pwd -P || true)"
    fi
    if [ -n "$script_dir" ] && looks_like_catalog "$script_dir"; then
      src="$script_dir"
      src_label="$src"
    else
      command -v git >/dev/null 2>&1 || die "git is required to fetch the catalog from $HARNESS_REPO"
      say "Fetching catalog from $HARNESS_REPO${git_ref:+ ($git_ref)} ..."
      if [ -n "$git_ref" ]; then
        git clone --quiet --depth 1 --branch "$git_ref" "$HARNESS_REPO" "$tmp_root/catalog"
      else
        git clone --quiet --depth 1 "$HARNESS_REPO" "$tmp_root/catalog"
      fi
      src="$tmp_root/catalog"
      src_label="$HARNESS_REPO${git_ref:+@$git_ref}"
    fi
  fi

  src_rev="$(git -C "$src" rev-parse --short HEAD 2>/dev/null || true)"
  [ -n "$src_rev" ] || src_rev="unknown"
}

resolve_target() {
  [ -d "$target" ] || die "target '$target' is not a directory"
  target="$(cd "$target" && pwd -P)"
  if [ -n "$src" ] && [ "$target" = "$src" ]; then
    die "refusing to install the catalog into itself; pass --target <consuming repo>"
  fi
}

# ---------------------------------------------------------------------------
# Frontmatter + body helpers (single-line values only, which is all the catalog uses)
# ---------------------------------------------------------------------------

# Raw value after "key: " inside the leading frontmatter block, quotes preserved.
fm_raw() {
  awk -v k="$1" '
    NR == 1 { if ($0 != "---") exit; next }
    $0 == "---" { exit }
    index($0, k ": ") == 1 { print substr($0, length(k) + 3); exit }
  ' "$2"
}

strip_quotes() {
  local v="$1"
  case "$v" in
    \'*\') v="${v#\'}"; v="${v%\'}" ;;
    \"*\") v="${v#\"}"; v="${v%\"}" ;;
  esac
  printf '%s' "$v"
}

fm_value() { strip_quotes "$(fm_raw "$1" "$2")"; }

# Everything after the closing "---"; the whole file when there is no frontmatter.
body_of() {
  awk '
    NR == 1 { if ($0 != "---") { p = 1; print } ; next }
    p { print; next }
    $0 == "---" { p = 1 }
  ' "$1"
}

# "a/b/c" -> "../../../"
up_prefix() {
  local d="$1" up="" seg
  if [ -z "$d" ] || [ "$d" = "." ]; then printf ''; return; fi
  local IFS=/
  for seg in $d; do
    [ -n "$seg" ] && up="../$up"
  done
  printf '%s' "$up"
}

# rewrite_links SRCDIR INSTALLED_DIR [KEEPROOT]
# Reads Markdown on stdin. Every relative link is resolved against SRCDIR (the
# file's directory inside the catalog) and re-pointed at the vendored catalog,
# computed relative to INSTALLED_DIR (the generated file's directory inside the
# target). Links that stay inside KEEPROOT (a folder copied as a unit, e.g. a
# skill with its references/) are left untouched. URLs, anchors, and absolute
# paths are never changed.
rewrite_links() {
  local srcdir="$1" installed_dir="$2" keeproot="${3:-}"
  local up
  up="$(up_prefix "$installed_dir")"
  awk -v srcdir="$srcdir" -v up="$up" -v cdir="$catalog_dir" -v keeproot="$keeproot" '
    function normalize(p,    n, parts, i, out, depth) {
      n = split(p, parts, "/"); out = ""; depth = 0
      for (i = 1; i <= n; i++) {
        if (parts[i] == "" || parts[i] == ".") continue
        if (parts[i] == "..") {
          if (depth == 0) return "<<escapes-catalog>>"
          sub(/\/?[^\/]*$/, "", out); depth--
        } else {
          out = (out == "" ? parts[i] : out "/" parts[i]); depth++
        }
      }
      return out
    }
    function rewrite(t,    path, frag, i, full, norm) {
      if (t == "" || t ~ /^#/ || t ~ /^\// || t ~ /^[A-Za-z][A-Za-z0-9+.-]*:/) return t
      i = index(t, "#")
      if (i > 0) { path = substr(t, 1, i - 1); frag = substr(t, i) } else { path = t; frag = "" }
      full = (srcdir == "" ? path : srcdir "/" path)
      norm = normalize(full)
      if (norm == "<<escapes-catalog>>") return t
      if (keeproot != "" && (norm == keeproot || index(norm, keeproot "/") == 1)) return t
      return up cdir "/" norm frag
    }
    {
      line = $0; out = ""
      while (match(line, /\]\([^)]*\)/)) {
        target = substr(line, RSTART + 2, RLENGTH - 3)
        out = out substr(line, 1, RSTART + 1) rewrite(target) ")"
        line = substr(line, RSTART + RLENGTH)
      }
      print out line
    }
  '
}

# "read, search, execute" -> Claude Code tool names
map_tools_claude() {
  local out="" t
  for t in $(printf '%s' "$1" | tr ',' ' '); do
    case "$t" in
      read) out="$out, Read" ;;
      search) out="$out, Grep, Glob" ;;
      execute) out="$out, Bash" ;;
      edit) out="$out, Edit, Write" ;;
      *) out="$out, $t" ;;
    esac
  done
  printf '%s' "${out#, }"
}

# ---------------------------------------------------------------------------
# Writing (every write goes through here so the manifest stays exact)
# ---------------------------------------------------------------------------

record() { printf '%s\n' "$1" >> "$manifest_tmp"; }

# write_file RELPATH  (content on stdin)
write_file() {
  local rel="$1" abs="$target/$1"
  record "$rel"
  if [ "$dry_run" = 1 ]; then cat > /dev/null; say "  + $rel"; return; fi
  mkdir -p "$(dirname "$abs")"
  cat > "$abs"
}

# copy_file SRC_ABS RELPATH
copy_file() {
  local from="$1" rel="$2" abs="$target/$2"
  record "$rel"
  if [ "$dry_run" = 1 ]; then say "  + $rel"; return; fi
  mkdir -p "$(dirname "$abs")"
  cp "$from" "$abs"
  if [ -x "$from" ]; then chmod +x "$abs"; fi
}

is_managed() { [ -f "$1" ] && grep -q "$MARKER" "$1"; }

# ---------------------------------------------------------------------------
# Generators
# ---------------------------------------------------------------------------

install_catalog() {
  say "Catalog -> $catalog_dir/"
  local item f
  for item in $CATALOG_ITEMS; do
    [ -e "$src/$item" ] || continue
    while IFS= read -r f; do
      copy_file "$src/$f" "$catalog_dir/$f"
      n_catalog=$((n_catalog + 1))
    done < <(cd "$src" && find "$item" -type f ! -name .DS_Store | LC_ALL=C sort)
  done
}

install_root_files() {
  [ "$touch_root" = 1 ] || return 0
  local label="AGENTS.md"
  has_harness claude && label="$label + CLAUDE.md"
  say "Contract -> $label"

  if [ -f "$target/AGENTS.md" ] && ! is_managed "$target/AGENTS.md" && [ "$force" = 0 ]; then
    warn "AGENTS.md exists and was not generated by this installer; left untouched. Add a pointer to $catalog_dir/AGENTS.md or re-run with --force."
  else
    {
      printf '<!-- %s from %s; source of truth is %s/AGENTS.md — re-run install.sh instead of editing -->\n' \
        "$MARKER" "$src_label" "$catalog_dir"
      rewrite_links "" "" < "$src/AGENTS.md"
    } | write_file "AGENTS.md"
    n_root=$((n_root + 1))
  fi

  if has_harness claude; then
    if [ -f "$target/CLAUDE.md" ] && ! is_managed "$target/CLAUDE.md" && [ "$force" = 0 ]; then
      if grep -q '^@AGENTS.md' "$target/CLAUDE.md"; then
        say "  = CLAUDE.md already imports @AGENTS.md"
      else
        warn "CLAUDE.md exists and was not generated by this installer; add the line '@AGENTS.md' to it or re-run with --force."
      fi
    else
      {
        printf '<!-- %s — re-run install.sh instead of editing -->\n' "$MARKER"
        printf '@AGENTS.md\n'
      } | write_file "CLAUDE.md"
      n_root=$((n_root + 1))
    fi
  fi
}

# install_rules HARNESS
install_rules() {
  local harness="$1" dest pack f name applies desc rel ext globs g
  case "$harness" in
    claude) dest=".claude/rules"; ext=".md" ;;
    copilot) dest=".github/instructions"; ext=".instructions.md" ;;
    cursor) dest=".cursor/rules"; ext=".mdc" ;;
    *) return 0 ;;
  esac
  say "Rules ($packs) -> $dest/"
  for pack in $packs; do
    for f in "$src/rules/$pack"/*.md; do
      [ -f "$f" ] || continue
      name="$(basename "$f" .md)"
      applies="$(fm_value appliesTo "$f")"
      desc="$(fm_raw description "$f")"
      rel="$dest/$pack-$name$ext"
      globs="$(printf '%s' "$applies" | sed 's/[[:space:]]*,[[:space:]]*/,/g')"
      {
        printf -- '---\n'
        [ -n "$desc" ] && printf 'description: %s\n' "$desc"
        case "$harness" in
          copilot)
            printf "applyTo: '%s'\n" "$applies"
            ;;
          claude)
            if [ "$applies" != "**/*" ] && [ -n "$applies" ]; then
              printf 'paths:\n'
              for g in $(printf '%s' "$globs" | tr ',' ' '); do printf "  - '%s'\n" "$g"; done
            fi
            ;;
          cursor)
            if [ "$applies" = "**/*" ] || [ -z "$applies" ]; then
              printf 'alwaysApply: true\n'
            else
              printf 'globs: %s\n' "$(printf '%s' "$globs" | sed 's/,/, /g')"
              printf 'alwaysApply: false\n'
            fi
            ;;
        esac
        printf -- '---\n'
        body_of "$f" | rewrite_links "rules/$pack" "$dest"
      } | write_file "$rel"
      n_rules=$((n_rules + 1))
    done
  done
}

# install_skills DEST_DIR  (copies every skill folder; links inside a skill stay, others go to the catalog)
install_skills() {
  local dest="$1" d name f reldir
  say "Skills -> $dest/"
  for d in "$src/skills"/*/; do
    [ -f "$d/SKILL.md" ] || continue
    name="$(basename "$d")"
    while IFS= read -r f; do
      reldir="$(dirname "$f")"
      case "$f" in
        *.md)
          rewrite_links "$reldir" "$dest/${reldir#skills/}" "skills/$name" < "$src/$f" | write_file "$dest/${f#skills/}"
          ;;
        *) copy_file "$src/$f" "$dest/${f#skills/}" ;;
      esac
    done < <(cd "$src" && find "skills/$name" -type f ! -name .DS_Store | LC_ALL=C sort)
    n_skills=$((n_skills + 1))
  done
}

# install_agents HARNESS
install_agents() {
  local harness="$1" f name desc tools dest rel
  case "$harness" in
    claude) dest=".claude/agents" ;;
    copilot) dest=".github/agents" ;;
    codex) dest=".agents/skills" ;;
    cursor) dest=".cursor/skills" ;;
  esac
  case "$harness" in
    claude | copilot) say "Agents -> $dest/" ;;
    *) say "Agents (as skills) -> $dest/" ;;
  esac
  for f in "$src/agents"/*.md; do
    name="$(basename "$f" .md)"
    [ "$name" = "README" ] && continue
    desc="$(fm_raw description "$f")"
    tools="$(fm_value tools "$f")"
    case "$harness" in
      claude)
        rel="$dest/$name.md"
        {
          printf -- '---\nname: %s\ndescription: %s\ntools: %s\n---\n' "$name" "$desc" "$(map_tools_claude "$tools")"
          body_of "$f" | rewrite_links "agents" "$dest"
        } | write_file "$rel"
        ;;
      copilot)
        rel="$dest/$name.agent.md"
        {
          printf -- '---\nname: %s\ndescription: %s\ntools: [%s]\n---\n' "$name" "$desc" \
            "$(printf '%s' "$tools" | sed "s/[[:space:]]*,[[:space:]]*/', '/g; s/^/'/; s/\$/'/")"
          body_of "$f" | rewrite_links "agents" "$dest"
        } | write_file "$rel"
        ;;
      codex | cursor)
        if [ -d "$src/skills/$name" ]; then
          warn "agent '$name' shares a name with a skill; not installed as a skill for $harness"
          continue
        fi
        rel="$dest/$name/SKILL.md"
        {
          printf -- '---\nname: %s\ndescription: %s\n---\n' "$name" "$desc"
          printf '\n> Read-only role. Allowed tools: %s. Do not edit files.\n' "$tools"
          body_of "$f" | rewrite_links "agents" "$dest/$name"
        } | write_file "$rel"
        ;;
    esac
    n_agents=$((n_agents + 1))
  done
}

# install_commands HARNESS
install_commands() {
  local harness="$1" f name desc hint dest rel
  case "$harness" in
    claude) dest=".claude/commands"; say "Commands -> $dest/" ;;
    copilot) dest=".github/skills"; say "Commands (as skills) -> $dest/" ;;
    codex) dest=".agents/skills"; say "Commands (as skills) -> $dest/" ;;
    cursor) dest=".cursor/skills"; say "Commands (as skills) -> $dest/" ;;
  esac
  for f in "$src/commands"/*.md; do
    name="$(basename "$f" .md)"
    [ "$name" = "README" ] && continue
    desc="$(fm_raw description "$f")"
    case "$harness" in
      claude)
        rel="$dest/$name.md"
        {
          printf -- '---\n'
          printf 'description: %s\n' "$desc"
          hint="$(fm_raw argument-hint "$f")"
          [ -n "$hint" ] && printf 'argument-hint: %s\n' "$hint"
          printf -- '---\n'
          body_of "$f" | rewrite_links "commands" "$dest"
        } | write_file "$rel"
        ;;
      *)
        if [ -d "$src/skills/$name" ]; then
          say "  = $name: skill of the same name already installed; command skipped"
          continue
        fi
        rel="$dest/$name/SKILL.md"
        {
          printf -- '---\nname: %s\ndescription: %s\n---\n' "$name" "$desc"
          body_of "$f" | rewrite_links "commands" "$dest/$name"
        } | write_file "$rel"
        ;;
    esac
    n_commands=$((n_commands + 1))
  done
}

guard_cmd() { printf '%s/hooks/scripts/guard-generated-files --stdin-json' "$1"; }

hook_config_content() {
  case "$1" in
    .claude/settings.json)
      cat <<EOF
{
  "hooks": {
    "PreToolUse": [
      {
        "matcher": "Edit|Write",
        "hooks": [
          { "type": "command", "command": "\${CLAUDE_PROJECT_DIR}/$(guard_cmd "$catalog_dir")" }
        ]
      }
    ]
  }
}
EOF
      ;;
    .github/hooks/guards.json)
      cat <<EOF
{
  "hooks": {
    "PreToolUse": [
      { "type": "command", "command": "$(guard_cmd "$catalog_dir")" }
    ]
  }
}
EOF
      ;;
    .cursor/hooks.json)
      cat <<EOF
{
  "version": 1,
  "hooks": {
    "preToolUse": [
      { "command": "$(guard_cmd "$catalog_dir")" }
    ]
  }
}
EOF
      ;;
  esac
}

# install_hook_config RELPATH — written only when absent (or previously ours); never merged.
install_hook_config() {
  local rel="$1"
  if [ -f "$target/$rel" ]; then
    if grep -q 'guard-generated-files' "$target/$rel"; then
      say "  = $rel already wires the guard"
    else
      warn "$rel exists; merge this hook yourself:"$'\n'"$(hook_config_content "$rel")"
    fi
    return 0
  fi
  hook_config_content "$rel" | write_file "$rel"
  n_hooks=$((n_hooks + 1))
}

install_hooks() {
  [ "$with_hooks" = 1 ] || return 0
  say "Hook configs"
  has_harness claude && install_hook_config ".claude/settings.json"
  has_harness copilot && install_hook_config ".github/hooks/guards.json"
  has_harness cursor && install_hook_config ".cursor/hooks.json"
  has_harness codex && say "  = codex: no pinned hook schema; use --git-hooks and CI (see $catalog_dir/hooks/README.md)"
  return 0
}

git_hook_content() {
  case "$1" in
    pre-commit)
      cat <<EOF
#!/bin/sh
# $MARKER — re-run install.sh --git-hooks instead of editing
root="\$(git rev-parse --show-toplevel)"
"\$root/$catalog_dir/hooks/scripts/guard-generated-files" --staged || exit 1
"\$root/$catalog_dir/hooks/scripts/format-gate" || exit 1
EOF
      ;;
    pre-push)
      cat <<EOF
#!/bin/sh
# $MARKER — re-run install.sh --git-hooks instead of editing
root="\$(git rev-parse --show-toplevel)"
"\$root/$catalog_dir/hooks/scripts/verify-gate" || exit 1
EOF
      ;;
  esac
}

install_git_hooks() {
  [ "$with_git_hooks" = 1 ] || return 0
  say "Git hooks -> .git/hooks/"
  local hooks_path hook rel
  if [ ! -d "$target/.git" ]; then
    warn "--git-hooks: $target is not a git repository root; skipped"
    return 0
  fi
  hooks_path="$(git -C "$target" config --get core.hooksPath 2>/dev/null || true)"
  if [ -n "$hooks_path" ]; then
    warn "--git-hooks: core.hooksPath is set ($hooks_path); add the hooks there yourself (see $catalog_dir/hooks/README.md)"
    return 0
  fi
  for hook in pre-commit pre-push; do
    rel=".git/hooks/$hook"
    if [ -f "$target/$rel" ] && ! is_managed "$target/$rel"; then
      warn "$rel exists and is not managed by this installer; left untouched (see $catalog_dir/hooks/README.md)"
      continue
    fi
    git_hook_content "$hook" | write_file "$rel"
    [ "$dry_run" = 1 ] || chmod +x "$target/$rel"
    n_hooks=$((n_hooks + 1))
  done
}

# ---------------------------------------------------------------------------
# Manifest + uninstall
# ---------------------------------------------------------------------------

manifest_path() { printf '%s/%s/%s' "$target" "$catalog_dir" "$MANIFEST_NAME"; }

write_manifest() {
  local rel="$catalog_dir/$MANIFEST_NAME"
  if [ "$dry_run" = 1 ]; then say "  + $rel"; return; fi
  mkdir -p "$target/$catalog_dir"
  {
    printf '# agent-harness install manifest — generated by install.sh; do not edit\n'
    printf '# source: %s @ %s\n' "$src_label" "$src_rev"
    printf '# installer: %s\n' "$INSTALLER_VERSION"
    printf '# date: %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
    printf '# options: --harness %s --packs %s --dir %s%s%s%s\n' \
      "$(printf '%s' "$harnesses" | tr ' ' ',')" "$(printf '%s' "$packs" | tr ' ' ',')" "$catalog_dir" \
      "$([ "$with_hooks" = 1 ] && printf ' --hooks')" \
      "$([ "$with_git_hooks" = 1 ] && printf ' --git-hooks')" \
      "$([ "$touch_root" = 0 ] && printf ' --no-root')"
    LC_ALL=C sort -u "$manifest_tmp"
  } > "$target/$catalog_dir/$MANIFEST_NAME"
}

# remove_path RELPATH — honours the safety rules for files users may own.
remove_path() {
  local rel="$1" abs="$target/$1"
  [ -e "$abs" ] || return 0
  case "$rel" in
    AGENTS.md | CLAUDE.md | .git/hooks/*)
      if ! is_managed "$abs"; then
        warn "$rel is not managed by this installer; left in place"
        return 0
      fi
      ;;
    .claude/settings.json | .github/hooks/guards.json | .cursor/hooks.json)
      if ! hook_config_content "$rel" | cmp -s - "$abs"; then
        warn "$rel was modified after install; left in place — remove the guard-generated-files hook yourself"
        return 0
      fi
      ;;
  esac
  if [ "$dry_run" = 1 ]; then say "  - $rel"; return 0; fi
  rm -f "$abs"
  local d
  d="$(dirname "$rel")"
  while [ "$d" != "." ] && [ "$d" != "/" ] && [ -d "$target/$d" ]; do
    rmdir "$target/$d" 2>/dev/null || break
    d="$(dirname "$d")"
  done
}

# remove_from_manifest QUIET(0|1)
remove_from_manifest() {
  local mp rel count=0
  mp="$(manifest_path)"
  [ -f "$mp" ] || return 1
  while IFS= read -r rel; do
    case "$rel" in "" | \#*) continue ;; esac
    case "$rel" in /* | *..*) warn "manifest entry '$rel' looks unsafe; skipped"; continue ;; esac
    remove_path "$rel"
    count=$((count + 1))
  done < "$mp"
  if [ "$dry_run" = 1 ]; then
    say "  - $catalog_dir/$MANIFEST_NAME"
  else
    rm -f "$mp"
    rmdir "$target/$catalog_dir" 2>/dev/null || true
  fi
  [ "$1" = 1 ] || say "Removed $count path(s) listed in $catalog_dir/$MANIFEST_NAME"
  return 0
}

run_uninstall() {
  resolve_target
  if [ ! -f "$(manifest_path)" ]; then
    die "no manifest at $catalog_dir/$MANIFEST_NAME in $target — nothing to uninstall (pass --dir if the catalog lives elsewhere)"
  fi
  if [ "$dry_run" = 1 ]; then
    say "Uninstalling agent harness from $target (dry run)"
  else
    say "Uninstalling agent harness from $target"
  fi
  remove_from_manifest 0
  print_warnings
}

print_warnings() {
  if [ -n "$warnings" ]; then
    printf '\nWarnings:\n%s' "$warnings"
  fi
}

# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

run_install() {
  resolve_source
  resolve_target
  harnesses="$(normalize_harnesses "$harness_arg")"
  packs="$(normalize_packs "$packs_arg")"
  manifest_tmp="$tmp_root/manifest"
  : > "$manifest_tmp"

  say "Installing agent harness"
  say "  source : $src_label @ $src_rev"
  say "  target : $target"
  say "  harness: $harnesses"
  say "  packs  : $packs"
  [ "$dry_run" = 1 ] && say "  mode   : dry run (nothing is written)"
  say ""

  if [ -f "$(manifest_path)" ]; then
    say "Previous install found; removing its files first"
    remove_from_manifest 1
    say ""
  fi

  install_catalog
  install_root_files

  local h
  for h in $harnesses; do
    say ""
    say "== $h"
    case "$h" in
      claude)
        install_rules claude
        install_skills ".claude/skills"
        install_agents claude
        install_commands claude
        ;;
      copilot)
        install_rules copilot
        install_skills ".github/skills"
        install_agents copilot
        install_commands copilot
        ;;
      codex)
        install_skills ".agents/skills"
        install_agents codex
        install_commands codex
        say "Rules: linked from AGENTS.md ($catalog_dir/rules/); Codex has no glob-scoped rule mechanism"
        ;;
      cursor)
        install_rules cursor
        install_skills ".cursor/skills"
        install_agents cursor
        install_commands cursor
        ;;
    esac
  done

  say ""
  install_hooks
  install_git_hooks
  write_manifest

  say ""
  say "Done. Installed: $n_catalog catalog files, $n_root root file(s), $n_rules rules, $n_skills skills, $n_agents agents, $n_commands commands, $n_hooks hook files."
  say ""
  say "Next steps:"
  say "  - Review the generated files and commit them (they are build outputs of $catalog_dir/, never edit them in place)."
  say "  - Re-run this exact command after upgrading the catalog; --uninstall removes everything listed in $catalog_dir/$MANIFEST_NAME."
  has_harness copilot && say "  - VS Code: keep chat.useAgentsMdFile on; enable chat.useCustomizationsInParentRepositories if the repo opens from a subfolder."
  if [ "$with_hooks" = 1 ] && has_harness copilot; then
    say "  - VS Code hooks are Preview: enable chat.useHooks and trust the workspace for .github/hooks/guards.json to run."
  fi
  has_harness codex && say "  - Codex: invoke skills with \$<name> or /skills; rules are reached through AGENTS.md links."
  [ "$with_hooks" = 1 ] || say "  - Optional: add --hooks (harness guards) and/or --git-hooks (pre-commit/pre-push) — see $catalog_dir/hooks/README.md."
  print_warnings
}

main() {
  parse_args "$@"
  if [ "$do_uninstall" = 1 ]; then
    run_uninstall
  else
    run_install
  fi
}

main "$@"
