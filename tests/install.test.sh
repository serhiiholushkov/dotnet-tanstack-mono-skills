#!/usr/bin/env bash
# tests/install.test.sh — end-to-end tests for install.sh.
# Runs the installer against throwaway targets and asserts the generated layout,
# frontmatter translation, link integrity, idempotency, protection of user-owned
# files, and uninstall. Dependency-free: bash, git, awk, sed, find.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
repo="$(cd "$here/.." && pwd -P)"
installer="$repo/install.sh"

work="$(mktemp -d 2>/dev/null || mktemp -d -t harness-tests)"
trap 'rm -rf "$work"' EXIT

pass=0
fail=0

ok() { pass=$((pass + 1)); printf '  ok   %s\n' "$1"; }
ko() { fail=$((fail + 1)); printf '  FAIL %s\n' "$1" >&2; }

assert_file() { if [ -f "$1" ]; then ok "exists: ${1#"$work"/}"; else ko "missing: ${1#"$work"/}"; fi; }
assert_missing() { if [ ! -e "$1" ]; then ok "absent: ${1#"$work"/}"; else ko "should be absent: ${1#"$work"/}"; fi; }
assert_grep() { if grep -q -- "$2" "$1" 2>/dev/null; then ok "${1#"$work"/} contains: $2"; else ko "${1#"$work"/} lacks: $2"; fi; }
assert_not_grep() { if ! grep -q -- "$2" "$1" 2>/dev/null; then ok "${1#"$work"/} omits: $2"; else ko "${1#"$work"/} must not contain: $2"; fi; }
assert_exec() { if [ -x "$1" ]; then ok "executable: ${1#"$work"/}"; else ko "not executable: ${1#"$work"/}"; fi; }
assert_eq() { if [ "$1" = "$2" ]; then ok "$3 = $2"; else ko "$3: expected '$2', got '$1'"; fi; }

# Every relative Markdown link in every .md/.mdc under DIR must resolve to an existing path.
assert_links_resolve() {
  local dir="$1" f dir_of t p links total=0 broken=0
  while IFS= read -r f; do
    dir_of="$(dirname "$f")"
    links="$(grep -o '](\([^)]*\))' "$f" | sed 's/^](//; s/)$//')" || true
    # Here-string rather than a nested process substitution: bash 3.2 (macOS) leaks fds there.
    while IFS= read -r t; do
      case "$t" in http://* | https://* | mailto:* | \#* | /* | "") continue ;; esac
      p="${t%%#*}"
      total=$((total + 1))
      if [ ! -e "$dir_of/$p" ]; then
        broken=$((broken + 1))
        printf '       broken: %s -> %s\n' "${f#"$dir"/}" "$t" >&2
      fi
    done <<< "$links"
  done < <(find "$dir" -path "$dir/.git" -prune -o \( -name '*.md' -o -name '*.mdc' \) -type f -print)
  if [ "$broken" = 0 ] && [ "$total" -gt 0 ]; then ok "all $total relative links resolve under ${dir#"$work"/}"; else ko "$broken of $total links broken under ${dir#"$work"/}"; fi
}

section() { printf '\n== %s\n' "$1"; }

# ---------------------------------------------------------------------------
section "full install, all harnesses, hooks"
t1="$work/t1"; mkdir -p "$t1"; git -C "$t1" init -q
"$installer" --target "$t1" --hooks --git-hooks > "$work/t1.log" 2>&1 || { cat "$work/t1.log"; ko "installer exited non-zero"; }

assert_file "$t1/AGENTS.md"
assert_grep "$t1/AGENTS.md" "agent-harness: generated by install.sh"
assert_grep "$t1/AGENTS.md" "](harness/docs/architecture.md)"
assert_file "$t1/CLAUDE.md"
assert_grep "$t1/CLAUDE.md" "^@AGENTS.md"
assert_file "$t1/harness/AGENTS.md"
assert_file "$t1/harness/docs/architecture.md"
assert_file "$t1/harness/skills/add-module/references/module-scaffold.md"
assert_exec "$t1/harness/hooks/scripts/guard-generated-files"
assert_file "$t1/harness/.install-manifest"
assert_grep "$t1/harness/.install-manifest" "^# options: --harness claude,copilot,codex,cursor"

# Claude
assert_file "$t1/.claude/rules/csharp-async.md"
assert_grep "$t1/.claude/rules/csharp-async.md" "^paths:"
assert_grep "$t1/.claude/rules/csharp-async.md" "  - 'apps/api/\*\*/\*.cs'"
assert_not_grep "$t1/.claude/rules/csharp-async.md" "appliesTo"
assert_not_grep "$t1/.claude/rules/common-naming.md" "^paths:"      # '**/*' rules load unconditionally
assert_grep "$t1/.claude/rules/testing-discipline.md" "  - 'apps/web/\*\*/\*.test.tsx'"
assert_file "$t1/.claude/skills/add-vertical-slice/SKILL.md"
assert_file "$t1/.claude/skills/add-vertical-slice/references/slice-examples.md"
assert_grep "$t1/.claude/skills/add-module/SKILL.md" "](references/module-scaffold.md)"   # in-skill link kept
assert_grep "$t1/.claude/skills/add-module/SKILL.md" "](../../../harness/docs/architecture.md"
assert_file "$t1/.claude/agents/boundary-auditor.md"
assert_grep "$t1/.claude/agents/boundary-auditor.md" "^tools: Read, Grep, Glob, Bash$"
assert_grep "$t1/.claude/agents/planner.md" "^tools: Read, Grep, Glob$"
assert_file "$t1/.claude/commands/plan.md"
assert_grep "$t1/.claude/commands/plan.md" "^argument-hint: <feature request or issue reference>$"
assert_grep "$t1/.claude/commands/plan.md" '[$]ARGUMENTS'
assert_file "$t1/.claude/settings.json"
assert_grep "$t1/.claude/settings.json" '[$]{CLAUDE_PROJECT_DIR}/harness/hooks/scripts/guard-generated-files --stdin-json'

# Copilot
assert_file "$t1/.github/instructions/web-routes.instructions.md"
assert_grep "$t1/.github/instructions/web-routes.instructions.md" "^applyTo: 'apps/web/src/routes/\*\*/\*.ts, apps/web/src/routes/\*\*/\*.tsx'$"
assert_not_grep "$t1/.github/instructions/web-routes.instructions.md" "^title:"
assert_file "$t1/.github/skills/regenerate-api-client/SKILL.md"
assert_file "$t1/.github/agents/contract-reviewer.agent.md"
assert_grep "$t1/.github/agents/contract-reviewer.agent.md" "^tools: \['read', 'search', 'execute'\]$"
assert_file "$t1/.github/skills/plan/SKILL.md"                 # command installed as a skill
assert_grep "$t1/.github/skills/plan/SKILL.md" "^name: plan$"
assert_missing "$t1/.github/prompts"
assert_file "$t1/.github/hooks/guards.json"

# Codex
assert_file "$t1/.agents/skills/add-ef-migration/SKILL.md"
assert_file "$t1/.agents/skills/planner/SKILL.md"              # agent installed as a skill
assert_grep "$t1/.agents/skills/planner/SKILL.md" "Read-only role"
assert_file "$t1/.agents/skills/implement/SKILL.md"
assert_missing "$t1/.agents/rules"

# Cursor
assert_file "$t1/.cursor/rules/common-boundaries.mdc"
assert_grep "$t1/.cursor/rules/common-boundaries.mdc" "^alwaysApply: true$"
assert_not_grep "$t1/.cursor/rules/common-boundaries.mdc" "^globs:"
assert_grep "$t1/.cursor/rules/dotnet-api-slices.mdc" "^globs: apps/api/src/Modules/\*\*/\*.cs$"
assert_grep "$t1/.cursor/rules/dotnet-api-slices.mdc" "^alwaysApply: false$"
assert_file "$t1/.cursor/skills/add-web-feature/SKILL.md"
assert_file "$t1/.cursor/hooks.json"

# Command/skill name collisions: the skill wins, the command is not duplicated as a skill
assert_grep "$t1/.cursor/skills/add-module/SKILL.md" "^name: add-module$"
assert_grep "$t1/.cursor/skills/add-module/SKILL.md" "Trigger terms"   # body is the skill, not the command
assert_grep "$work/t1.log" "add-module: skill of the same name already installed; command skipped"

# Git hooks
assert_exec "$t1/.git/hooks/pre-commit"
assert_grep "$t1/.git/hooks/pre-commit" "harness/hooks/scripts/guard-generated-files\" --staged"
assert_exec "$t1/.git/hooks/pre-push"
assert_grep "$t1/.git/hooks/pre-push" "harness/hooks/scripts/verify-gate"

assert_links_resolve "$t1"

# ---------------------------------------------------------------------------
section "re-install is idempotent and removes stale files"
touch "$t1/.claude/skills/stale-skill.md"
printf 'x\n' > "$t1/harness/rules/common/stale.md"
# Simulate a stale entry from a previous catalog version by appending it to the manifest.
printf '.claude/skills/stale-skill.md\nharness/rules/common/stale.md\n' >> "$t1/harness/.install-manifest"
before="$(find "$t1" -path "$t1/.git" -prune -o -type f -print | LC_ALL=C sort | wc -l | tr -d ' ')"
"$installer" --target "$t1" --hooks --git-hooks > "$work/t1b.log" 2>&1 || ko "re-install exited non-zero"
assert_grep "$work/t1b.log" "Previous install found; removing its files first"
assert_missing "$t1/.claude/skills/stale-skill.md"
assert_missing "$t1/harness/rules/common/stale.md"
after="$(find "$t1" -path "$t1/.git" -prune -o -type f -print | LC_ALL=C sort | wc -l | tr -d ' ')"
assert_eq "$after" "$((before - 2))" "file count after re-install"
assert_links_resolve "$t1"

# ---------------------------------------------------------------------------
section "uninstall removes everything and nothing else"
printf 'keep me\n' > "$t1/README.md"
"$installer" --target "$t1" --uninstall > "$work/t1c.log" 2>&1 || ko "uninstall exited non-zero"
assert_file "$t1/README.md"
assert_missing "$t1/AGENTS.md"
assert_missing "$t1/CLAUDE.md"
assert_missing "$t1/harness"
assert_missing "$t1/.claude"
assert_missing "$t1/.github"
assert_missing "$t1/.agents"
assert_missing "$t1/.cursor"
assert_missing "$t1/.git/hooks/pre-commit"
assert_missing "$t1/.git/hooks/pre-push"
assert_file "$t1/.git/HEAD"

# ---------------------------------------------------------------------------
section "subset install; user-owned root files are never clobbered"
t2="$work/t2"; mkdir -p "$t2"
printf '# Mine\n' > "$t2/AGENTS.md"
printf 'mine\n' > "$t2/CLAUDE.md"
"$installer" --target "$t2" --harness claude --packs api > "$work/t2.log" 2>&1 || ko "subset install exited non-zero"
assert_eq "$(cat "$t2/AGENTS.md")" "# Mine" "unmanaged AGENTS.md content"
assert_eq "$(cat "$t2/CLAUDE.md")" "mine" "unmanaged CLAUDE.md content"
assert_grep "$work/t2.log" "warning: AGENTS.md exists and was not generated by this installer"
assert_grep "$work/t2.log" "warning: CLAUDE.md exists and was not generated by this installer"
assert_eq "$(find "$t2/.claude/rules" -type f | wc -l | tr -d ' ')" "20" "api role rule count (common+csharp+dotnet-api+testing)"
assert_missing "$t2/.claude/rules/web-routes.md"
assert_missing "$t2/.claude/rules/typescript-types.md"
assert_missing "$t2/.github"
assert_missing "$t2/.cursor"
assert_missing "$t2/.agents"
assert_links_resolve "$t2"

section "--force takes over root files; --dir relocates the catalog"
"$installer" --target "$t2" --harness claude --packs api --force --dir .harness > "$work/t2b.log" 2>&1 || ko "--force install exited non-zero"
assert_grep "$t2/AGENTS.md" "agent-harness: generated by install.sh"
assert_grep "$t2/AGENTS.md" "](.harness/docs/architecture.md)"
assert_grep "$t2/CLAUDE.md" "^@AGENTS.md"
assert_file "$t2/.harness/.install-manifest"
assert_grep "$t2/.claude/skills/add-module/SKILL.md" "](../../../.harness/docs/architecture.md"
assert_links_resolve "$t2"

# ---------------------------------------------------------------------------
section "dry run writes nothing"
t3="$work/t3"; mkdir -p "$t3"
"$installer" --target "$t3" --dry-run --hooks > "$work/t3.log" 2>&1 || ko "dry run exited non-zero"
assert_eq "$(find "$t3" -type f | wc -l | tr -d ' ')" "0" "files written by dry run"
assert_grep "$work/t3.log" "  + .claude/skills/add-module/SKILL.md"
assert_grep "$work/t3.log" "  + harness/.install-manifest"

# ---------------------------------------------------------------------------
section "argument validation"
if "$installer" --target "$t3" --dir a/b > "$work/v1.log" 2>&1; then ko "--dir a/b accepted"; else assert_grep "$work/v1.log" "single folder name"; fi
if "$installer" --target "$t3" --harness nope > "$work/v2.log" 2>&1; then ko "--harness nope accepted"; else assert_grep "$work/v2.log" "unknown harness 'nope'"; fi
if "$installer" --target "$t3" --packs nope > "$work/v3.log" 2>&1; then ko "--packs nope accepted"; else assert_grep "$work/v3.log" "unknown rule pack 'nope'"; fi
if (cd "$repo" && "$installer" --dry-run > "$work/v4.log" 2>&1); then ko "installing into the catalog itself accepted"; else assert_grep "$work/v4.log" "refusing to install the catalog into itself"; fi
if "$installer" --target "$t3" --uninstall > "$work/v5.log" 2>&1; then ko "uninstall without manifest accepted"; else assert_grep "$work/v5.log" "no manifest"; fi

# ---------------------------------------------------------------------------
section "piped mode clones the catalog (curl | bash)"
t4="$work/t4"; mkdir -p "$t4"
# Run from the catalog root on purpose: a piped script must still clone rather than
# mistake the current directory for its own checkout (regressed on bash 5 in CI).
if (cd "$repo" && HARNESS_REPO="$repo" bash -s -- --target "$t4" --harness codex < "$installer") > "$work/t4.log" 2>&1; then
  ok "piped install exited zero"
else
  cat "$work/t4.log" >&2; ko "piped install exited non-zero"
fi
assert_grep "$work/t4.log" "Fetching catalog from"
assert_file "$t4/.agents/skills/add-vertical-slice/SKILL.md"
assert_file "$t4/AGENTS.md"
assert_missing "$t4/CLAUDE.md"
assert_links_resolve "$t4"

# ---------------------------------------------------------------------------
printf '\n%d passed, %d failed\n' "$pass" "$fail"
[ "$fail" = 0 ]
